    return "تقدر تستخدم حاسبة السعر عشان تاخد تقدير مبدئي. السعر النهائي بيتأكد بعد مراجعة تفاصيل المكان والصور والتجهيزات، فمهم ما نعتبرش التقدير مقايسة نهائية.";
