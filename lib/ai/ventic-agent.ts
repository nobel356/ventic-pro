export function assistantPrompt(input: {
  path: string;
  history: AgentHistoryItem[];
  message: string;
}) {
  const conversation = input.history
    .slice(-6)
    .map(
      (item) =>
        `${item.role === "user" ? "العميل" : "المساعد"}: ${item.text}`,
    )
    .join("\n");

  return [
    `الصفحة الحالية: ${input.path || "/"}`,
    conversation
      ? `المحادثة السابقة:\n${conversation}`
      : "",
    `رسالة العميل الحالية:\n${input.message}`,
    "",
    "أجب مباشرة في حدود 2-6 جمل غالبًا. لا تضع روابط كاملة؛ الواجهة ستعرض أزرار المتابعة.",
  ]
    .filter(Boolean)
    .join("\n\n");
}
